def arc_center(x0, y0, x1, y1, r, large, sweep):
    """Calculate arc center from endpoints, radius, large-arc and sweep flags."""
    dx = x1 - x0
    dy = y1 - y0
    d = math.sqrt(dx*dx + dy*dy)
    if d > 2*r:
        r = d/2 + 0.01  # clamp
    a = d / 2
    h = math.sqrt(max(r*r - a*a, 0))
    mx = (x0 + x1) / 2
    my = (y0 + y1) / 2
    # Two possible centers
    cx1 = mx + h * (y0 - y1) / d
    cy1 = my + h * (x1 - x0) / d
    cx2 = mx - h * (y0 - y1) / d
    cy2 = my - h * (x1 - x0) / d
    # Choose center based on large-arc and sweep
    if (large == 0 and sweep == 1) or (large == 1 and sweep == 0):
        return cx1, cy1
    else:
        return cx2, cy2

def write_dxf(filepath, curves):
    lines = []
    lines.append("0\nSECTION\n2\nHEADER\n0\nENDSEC")
    lines.append("0\nSECTION\n2\nENTITIES")

    for curve in curves:
        p = curve.split('|')
        if p[0] == 'L':
            x0, y0, x1, y1 = float(p[1]), float(p[2]), float(p[3]), float(p[4])
            lines.append(f"0\nLINE\n8\n0\n10\n{x0}\n20\n{y0}\n30\n0\n11\n{x1}\n21\n{y1}\n31\n0")
        elif p[0] == 'A':
            x0, y0 = float(p[1]), float(p[2])
            x1, y1 = float(p[3]), float(p[4])
            r = float(p[5])
            la, sf = int(p[6]), int(p[7])
            cx, cy = arc_center(x0, y0, x1, y1, r, la, sf)
            sa = math.degrees(math.atan2(y0 - cy, x0 - cx))
            ea = math.degrees(math.atan2(y1 - cy, x1 - cx))
            if sa < 0: sa += 360
            if ea < 0: ea += 360
            # DXF ARC goes CCW from start to end angle
            if sf == 1:  # CCW - normal DXF order
                lines.append(f"0\nARC\n8\n0\n10\n{cx}\n20\n{cy}\n30\n0\n40\n{r}\n50\n{sa}\n51\n{ea}")
            else:  # CW - swap start/end
                lines.append(f"0\nARC\n8\n0\n10\n{cx}\n20\n{cy}\n30\n0\n40\n{r}\n50\n{ea}\n51\n{sa}")

    lines.append("0\nENDSEC\n0\nEOF")
    with open(filepath, 'w') as f:
        f.write('\n'.join(lines))

