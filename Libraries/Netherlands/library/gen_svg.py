db_comps = []
for c in data:
    bb = c['bb']
    pad = 2
    # Flip Y: negate all Y coords, so miny becomes -maxy
    ny_min = -bb[3]
    ny_max = -bb[1]
    vx = bb[0] - pad
    vy = ny_min - pad
    vw = bb[2] - bb[0] + 2*pad
    vh = ny_max - ny_min + 2*pad
    sw = max(vw, vh) * 0.004

    elems = []
    for curve in c['curves']:
        p = curve.split('|')
        if p[0] == 'L':
            x0, y0, x1, y1 = float(p[1]), -float(p[2]), float(p[3]), -float(p[4])
            elems.append(f'<line x1="{x0}" y1="{y0}" x2="{x1}" y2="{y1}"/>')
        elif p[0] == 'A':
            x0, y0 = float(p[1]), -float(p[2])
            x1, y1 = float(p[3]), -float(p[4])
            r = float(p[5])
            la = int(p[6])
            sf = int(p[7])  # keep original sweep, Y-flip handled by negating coords
            elems.append(f'<path d="M{x0} {y0} A{r} {r} 0 {la} {sf} {x1} {y1}"/>')

    h = 300 * vh / vw if vw > 0 else 300
    svg = f'''<?xml version="1.0" encoding="UTF-8"?>
<svg xmlns="http://www.w3.org/2000/svg" viewBox="{vx} {vy} {vw} {vh}" width="300" height="{h:.0f}">
<g stroke="#333" stroke-width="{sw:.3f}" fill="none" stroke-linecap="round" stroke-linejoin="round">
{chr(10).join(elems)}
</g>
</svg>'''

    fname = re.sub(r'[^a-zA-Z0-9_\-.]', '', (c['fam'].strip()+'__'+c['typ']).replace(' ','_').replace('/','_')) + '.svg'
    with open(os.path.join(svg_dir, fname), 'w') as f:
        f.write(svg)

    db_comps.append({
        'element_id': c['eid'], 'type_id': c['tid'],
        'family': c['fam'], 'type': c['typ'],
        'width_mm': round(bb[2]-bb[0],1), 'height_mm': round(bb[3]-bb[1],1),
        'curves': len(c['curves']), 'svg': 'components/svg/' + fname
    })

